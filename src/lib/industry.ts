export interface DetectedIndustry {
  id: IndustryId;
  label: string;
}

export function industryById(id: IndustryId | undefined): IndustryProfile {
  return INDUSTRIES.find((p) => p.id === id) ?? OTHER_INDUSTRY;
}

function countMatches(text: string, re: RegExp): number {
  return text ? (text.match(new RegExp(re.source, "g")) ?? []).length : 0;
}

/** サイトの文字から業種を推定する。手がかりが少なければ "other" */
export function detectIndustry(parts: { title: string; description: string; h1: string[]; headings: string[]; text: string }): DetectedIndustry {
  let best: { p: IndustryProfile; score: number } | null = null;
  for (const p of INDUSTRIES) {
    const score =
      countMatches(parts.title, p.pattern) * 4 +
      countMatches(parts.description, p.pattern) * 2 +
      countMatches(parts.h1.join(" "), p.pattern) * 2 +
      countMatches(parts.headings.join(" "), p.pattern) +
      Math.min(countMatches(parts.text, p.pattern), 10) * 0.5;
    if (!best || score > best.score) best = { p, score };
  }
  if (!best || best.score < 3) return { id: "other", label: OTHER_INDUSTRY.label };
  return { id: best.p.id, label: best.p.label };
}

/**
 * 営業担当が入力した業種を優先し、なければ自動判定の結果を使う。
 * 入力が業種の一覧に当てはまらない場合は「その他」の素材を使い、表示名だけ入力どおりにする。
 */
export function resolveIndustry(userInput: string | undefined, detected: DetectedIndustry | undefined): { profile: IndustryProfile; label: string; auto: boolean } {
  const input = userInput?.trim();
  if (input) {
    const matched = INDUSTRIES.map((p) => ({ p, n: countMatches(input, p.pattern) }))
      .filter((x) => x.n > 0)
      .sort((a, b) => b.n - a.n)[0];
    return { profile: matched?.p ?? OTHER_INDUSTRY, label: input, auto: false };
  }
  const profile = industryById(detected?.id);
  return { profile, label: profile.label, auto: true };
}
